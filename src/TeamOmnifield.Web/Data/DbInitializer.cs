    public static async Task InitializeAsync(AppDbContext db, IPasswordHasher<AdminUser> hasher)
    {
        for (var attempt = 1; attempt <= 20; attempt++)
        {
            try
            {
                await db.Database.EnsureCreatedAsync();
                break;
            }
            catch when (attempt < 20)
            {
                await Task.Delay(1000);
            }
        }

        // EnsureCreated skips tables added after the database first existed, so create the customer table explicitly.
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS "Customers" (
                "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                "FullName" text NOT NULL,
                "Email" text NOT NULL,
                "Phone" text NOT NULL,
                "PasswordHash" text NOT NULL,
                "IsActive" boolean NOT NULL DEFAULT TRUE,
                "CreatedUtc" timestamp with time zone NOT NULL DEFAULT NOW()
            )
            """);
        await db.Database.ExecuteSqlRawAsync("""CREATE UNIQUE INDEX IF NOT EXISTS "IX_Customers_Email" ON "Customers" ("Email")""");

        // Same reason as "Customers": the platform's client table arrived after the database first existed.
        await db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS "PlatformClients" (
                "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                "Name" text NOT NULL,
                "City" text NOT NULL DEFAULT '',
                "Contact" text NOT NULL,
                "ContactEmail" text NOT NULL,
                "Domain" text NOT NULL,
                "AdminDomain" text NOT NULL,
                "Stage" text NOT NULL DEFAULT 'New',
                "IsActive" boolean NOT NULL DEFAULT TRUE,
                "IsBuiltIn" boolean NOT NULL DEFAULT FALSE,
                "CreatedUtc" timestamp with time zone NOT NULL DEFAULT NOW(),
                "UpdatedUtc" timestamp with time zone NOT NULL DEFAULT NOW()
            )
            """);
        await db.Database.ExecuteSqlRawAsync("""CREATE UNIQUE INDEX IF NOT EXISTS "IX_PlatformClients_Domain" ON "PlatformClients" ("Domain")""");

        if (!await db.Categories.AnyAsync())
        {
            var categories = new[]
            {
                new Category { Name = "Biryani", DisplayOrder = 1 },
                new Category { Name = "Starters", DisplayOrder = 2 },
                new Category { Name = "Meals", DisplayOrder = 3 },
                new Category { Name = "Beverages", DisplayOrder = 4 },
                new Category { Name = "Desserts", DisplayOrder = 5 }
            };
            db.Categories.AddRange(categories);
            await db.SaveChangesAsync();
        }

        await db.Database.ExecuteSqlRawAsync("""ALTER TABLE "Products" ADD COLUMN IF NOT EXISTS "ImageUrl" text NOT NULL DEFAULT ''""");
        await db.Database.ExecuteSqlRawAsync("""CREATE UNIQUE INDEX IF NOT EXISTS "IX_Products_Name_Unique" ON "Products" (LOWER("Name"))""");
        await db.Database.ExecuteSqlRawAsync("""ALTER TABLE "Orders" ADD COLUMN IF NOT EXISTS "PaymentMethod" text NOT NULL DEFAULT ''""");
        await db.Database.ExecuteSqlRawAsync("""ALTER TABLE "Orders" ADD COLUMN IF NOT EXISTS "City" text NOT NULL DEFAULT ''""");
        // Orders placed before locations were tracked came from the original (Chennai) storefront.
        await db.Database.ExecuteSqlRawAsync("""UPDATE "Orders" SET "City" = 'chennai' WHERE "City" = ''""");

        {
            var categories = await db.Categories.ToDictionaryAsync(x => x.Name);
            var existingNames = (await db.Products.Select(x => x.Name).ToListAsync())
                .ToHashSet(StringComparer.OrdinalIgnoreCase);

            var missing = ProductSeeds
                .Where(seed => !existingNames.Contains(seed.Name))
                .Select(seed => new Product
                {
                    CategoryId = categories[seed.CategoryName].Id,
                    Name = seed.Name,
                    Description = seed.Description,
                    Price = seed.Price,
                    ImageUrl = ProductImages.TryGetValue(seed.Name, out var url) ? url : DefaultImage
                })
                .ToList();

            if (missing.Count > 0)
            {
                db.Products.AddRange(missing);
                await db.SaveChangesAsync();
            }

            // loremflickr links are random and often fail to load; swap them for the curated photos.
            var unpictured = await db.Products.Where(x => x.ImageUrl == "" || x.ImageUrl.Contains("loremflickr.com")).ToListAsync();
            foreach (var product in unpictured)
            {
                product.ImageUrl = ProductImages.TryGetValue(product.Name, out var url) ? url : DefaultImage;
            }
            if (unpictured.Count > 0) await db.SaveChangesAsync();
        }

        // Seeded per account, so an existing database still picks up accounts added later.
        var seededUsers = new[]
        {
            ("admin@htrestaurant.com", "HT Restaurant Owner"),
            ("developer@htrestaurant.com", "TeamOmnifield Consultant"),
        };

        var added = false;
        foreach (var (email, displayName) in seededUsers)
        {
            if (await db.AdminUsers.AnyAsync(x => x.Email == email)) continue;
            var user = new AdminUser { Email = email, DisplayName = displayName };
            user.PasswordHash = hasher.HashPassword(user, "Admin@12345");
            db.AdminUsers.Add(user);
            added = true;
        }
        if (added) await db.SaveChangesAsync();
    }

